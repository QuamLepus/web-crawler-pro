class Services:
    """Container built once per app; swappable in tests via ``app.state.services``."""

    def __init__(self, redis_client) -> None:
        self.redis = redis_client
        self.users = UserStore(redis_client)
        self.api_keys = _make_keystore(redis_client)
        self.quotas = QuotaService(redis_client, plan_resolver=self.plan_for)
        self.rate = RateLimiter(redis_client)
        self.billing = BillingService(self.users, redis_client)
        self.webhooks = WebhookService(redis_client)
        self.scheduler = _make_scheduler(redis_client)

    def plan_for(self, tenant: str):
        org = self.users.get_org(tenant)
        return get_plan(org.plan if org else "free")


def _make_keystore(redis_client):
    from src.gateway.auth.tokens import ApiKeyStore

    return ApiKeyStore(redis_client)


def _make_scheduler(redis_client):
    try:
        from src.celery_app import celery_app
    except Exception:
        celery_app = None
    from src.compute.scheduler import SchedulerService

    return SchedulerService(redis_client, celery_app=celery_app)


def _default_redis():
    try:
        import redis

        return redis.Redis.from_url(REDIS_URL, decode_responses=False)
    except Exception as exc:  # pragma: no cover - connection refused in dev
        logger.warning("redis unavailable (%s); falling back to fakeredis", exc)
        import fakeredis

        return fakeredis.FakeRedis(decode_responses=False)


def get_services(request: Request) -> Services:
    return request.app.state.services


Svc = Annotated[Services, Depends(get_services)]

