async def current_user(svc: Svc,
                       token: Annotated[Optional[str], Depends(oauth2_scheme)]):
    if token is None:
        return None  # api-key-only requests are allowed; ctx dependency decides
    try:
        claims = decode_token(token)
    except TokenExpired:
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, "token expired",
                            headers={"WWW-Authenticate": "Bearer"})
    except TokenInvalid:
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, "invalid token",
                            headers={"WWW-Authenticate": "Bearer"})
    if claims.get("typ") != "access":
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, "wrong token type")
    user = svc.users.get_user(claims["sub"])
    if user is None or user.disabled or svc.users.is_locked(user.id):
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, "user unavailable")
    return user


async def api_key_ctx(
    svc: Svc,
    x_api_key: Annotated[Optional[str], Header()] = None,
    user=Depends(current_user),
):
    """Either an API key (machine) or a JWT user (human) identifies the tenant.

    Rate limiting + quota metering attach to whichever principal is present;
    API keys take precedence for machine traffic.
    """
    if x_api_key:
        ak = svc.api_keys.lookup(x_api_key)
        if ak is None:
            raise HTTPException(status.HTTP_401_UNAUTHORIZED, "bad api key")
        return {"principal": "apikey", "tenant": ak.tenant, "key_id": ak.key_id,
                "scopes": ak.scopes, "role": "member", "user": None}
    if user is None:
        raise HTTPException(status.HTTP_401_UNAUTHORIZED,
                            "provide Authorization: Bearer <jwt> or X-API-Key")
    return {"principal": "jwt", "tenant": user.tenant, "key_id": user.id,
            "scopes": ["read", "crawl", "admin"], "role": user.role, "user": user}


Ctx = Annotated[dict, Depends(api_key_ctx)]


def require_role(ctx: dict, minimum: str) -> None:
    from src.gateway.auth.users import ROLE_RANK

    if ctx["principal"] == "apikey":
        if minimum in ("admin", "owner"):
            raise HTTPException(status.HTTP_403_FORBIDDEN, "admin scope required")
        return
    rank = ROLE_RANK.get(ctx["role"], -1)
    if rank < ROLE_RANK[minimum]:
        raise HTTPException(status.HTTP_403_FORBIDDEN, f"requires {minimum} role")


# --------------------------------------------------------------------------- #
# Rate-limit enforcement helper
# --------------------------------------------------------------------------- #
def enforce_rate_limit(svc: Services, ctx: dict, endpoint: str,
                       request: Request) -> dict[str, str]:
    plan = svc.plan_for(ctx["tenant"])
    q = plan.quotas
    # 1) per-principal token bucket (sustained rate w/ burst)
    res = svc.rate.token_bucket(
        f"key:{ctx['key_id']}", capacity=q.burst_per_minute,
        refill_per_sec=q.api_rate_per_minute / 60.0,
    )
    if not res.allowed:
        raise HTTPException(status.HTTP_429_TOO_MANY_REQUESTS,
                            "rate limit exceeded", headers=res.headers())
    # 2) per-tenant per-endpoint sliding window (abuse guard)
    win = svc.rate.sliding_window(
        f"{ctx['tenant']}:{endpoint}", limit=max(q.api_rate_per_minute * 5, 300),
        window_s=300, member=f"{time.time_ns()}-{uuid.uuid4().hex[:6]}")
    if not win.allowed:
        raise HTTPException(status.HTTP_429_TOO_MANY_REQUESTS,
                            "endpoint window exceeded", headers=win.headers())
    return res.headers()


